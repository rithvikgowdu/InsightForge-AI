
import type { AnalysisResult } from "../../services/api";

type ReportOpportunitiesProps = {
  results?: AnalysisResult[];
};

function ReportOpportunities({
  results = [],
}: ReportOpportunitiesProps) {
  const opportunities = results.flatMap((result) => {
    const value = result.opportunity;

    if (!value || typeof value !== "object") {
      return [];
    }

    const data = value as Record<string, unknown>;

    const title =
      data.title ??
      data.name ??
      data.opportunity ??
      data.opportunityTitle ??
      data.opportunity_title;

    const description =
      data.description ??
      data.summary ??
      data.rationale;

    const mvp =
      data.mvp ??
      data.mvpFeatures ??
      data.mvp_features ??
      data.recommendedMvp ??
      data.recommended_mvp;

    const hasContent =
      typeof title === "string" ||
      typeof description === "string";

    if (!hasContent) {
      return [];
    }

    return [
      {
        key: String(result.cluster),
        cluster: result.cluster,
        title:
          typeof title === "string"
            ? title
            : `Opportunity from Cluster ${result.cluster}`,
        description:
          typeof description === "string"
            ? description
            : result.summary,
        mvp: Array.isArray(mvp)
          ? mvp.filter(
              (item): item is string => typeof item === "string"
            ).join(", ")
          : typeof mvp === "string"
            ? mvp
            : "",
      },
    ];
  });

  return (
    <section>
      <div className="mb-5">
        <h2 className="text-2xl font-semibold text-white">
          Product Opportunities
        </h2>

        <p className="mt-1 text-sm text-slate-400">
          Opportunities generated by the repository analysis.
          Scores are shown only when supported by the returned data.
        </p>
      </div>

      {opportunities.length === 0 ? (
        <div className="rounded-xl border border-slate-800 bg-slate-900 p-6">
          <p className="text-sm leading-6 text-slate-400">
            No product opportunities are available yet. Complete an
            analysis that returns opportunity details to populate this
            section.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-2">
          {opportunities.map((opportunity) => (
            <div
              key={opportunity.key}
              className="rounded-xl border border-slate-800 bg-slate-900 p-6 shadow-lg"
            >
              <div className="flex items-start justify-between gap-4">
                <h3 className="text-lg font-semibold text-white">
                  {opportunity.title}
                </h3>

                <span className="whitespace-nowrap rounded-full bg-slate-800 px-3 py-1 text-sm font-medium text-slate-300">
                  Cluster {opportunity.cluster}
                </span>
              </div>

              <p className="mt-4 text-sm leading-6 text-slate-400">
                {opportunity.description}
              </p>

              {opportunity.mvp && (
                <div className="mt-5 border-t border-slate-800 pt-5">
                  <p className="text-xs font-medium uppercase tracking-wide text-slate-500">
                    Recommended MVP
                  </p>

                  <p className="mt-2 text-sm leading-6 text-slate-300">
                    {opportunity.mvp}
                  </p>
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </section>
  );
}

export default ReportOpportunities;
